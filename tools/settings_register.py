"""The settings register: every XESTRATA_* environment setting the engine and its entries read, in one file
(data/settings-register.json).  upstream 89f4fa18's settings register, written for XeStrata's readers: the engine reads
`strata::env_get("NAME")` (and the local helpers that call it), serve/ and setup.py read `envvars.get("NAME")`, the
launcher reads `XESTRATA_*` through launcher/Core/Platform.fs, and the shell scripts read `$XESTRATA_NAME`.

    python tools/settings_register.py             # write data/settings-register.json
    python tools/settings_register.py --check     # scan only; print what is missing from / extra in the register;
                                                 # exit 1 on a name difference
    python tools/settings_register.py --names     # print the names that are read, one per line

What counts as a read: the name is the string literal argument of an engine env helper (`env_get`, `env_on`, `env_off`,
`env_or`, `env_mib`, `env_isa_cap`, `env_auto`), of `envvars.get` in Python, a `XESTRATA_*` string in the launcher's F#, or a
`$XESTRATA_*` reference in a shell script.  A call whose argument is not a literal (a computed name) is not listed: it
cannot be enumerated.

The register is generated; only the names and their read sites are in it, with no hand-kept fields.  `--check` compares
the NAMES (a new setting must be added by running the tool; the read sites' line numbers are refreshed by the same run).
"""
from __future__ import annotations

import argparse
import json
import os
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REGISTER = ROOT / "data" / "settings-register.json"

ENGINE_DIRS = ("src", "include")
PY_DIRS = ("serve", "tools")
PY_FILES = ("setup.py",)
LAUNCHER_FILES = ("launcher/Core/Platform.fs",)
SHELL_GLOBS = ("setup.sh", "tools", "container")
SKIP_PARTS = ("node_modules", "__pycache__", "/build/", "/.tools/", "/.lint/", "/third_party/")

CPP_CALL = re.compile(r'\b(?:env_get|env_on|env_off|env_or|env_mib|env_isa_cap|env_auto)\s*\(\s*"([A-Z0-9_]+)"')
PY_CALL = re.compile(r'\benvvars\.get\s*\(\s*"([A-Z0-9_]+)"')
FS_NAME = re.compile(r'"(XESTRATA_[A-Z0-9_]+)"')
SH_NAME = re.compile(r'\$\{?(XESTRATA_[A-Z0-9_]+)')
LEGACY = re.compile(r'\bSTRATA_[A-Z0-9_]+')


def _walk(paths, exts):
    for rel in paths:
        base = ROOT / rel
        if base.is_file():
            yield base
            continue
        for dirpath, dirnames, filenames in os.walk(base):
            dirnames[:] = [d for d in dirnames if not any(p in (Path(dirpath) / d).as_posix() for p in SKIP_PARTS)]
            for fn in sorted(filenames):
                if exts and not fn.endswith(exts):
                    continue
                p = Path(dirpath) / fn
                if any(p.as_posix().find(s) >= 0 for s in SKIP_PARTS):
                    continue
                yield p


def _lines(path):
    try:
        return path.read_text(encoding="utf-8", errors="replace").splitlines()
    except OSError:
        return []


def _rel(path):
    return path.relative_to(ROOT).as_posix()


def scan():
    """{name: ["file:line", ...]} - every setting read through a literal name."""
    found: dict[str, list[str]] = {}

    def add(name, where):
        found.setdefault(name, []).append(where)

    for p in _walk(ENGINE_DIRS, (".cpp", ".hpp", ".h", ".cc")):
        for i, line in enumerate(_lines(p), 1):
            for m in CPP_CALL.finditer(line):
                add(m.group(1), f"{_rel(p)}:{i}")
    for p in list(_walk(PY_DIRS, (".py",))) + [ROOT / f for f in PY_FILES if (ROOT / f).is_file()]:
        for i, line in enumerate(_lines(p), 1):
            for m in PY_CALL.finditer(line):
                add(m.group(1), f"{_rel(p)}:{i}")
    for f in LAUNCHER_FILES:
        p = ROOT / f
        if not p.is_file():
            continue
        for i, line in enumerate(_lines(p), 1):
            for m in FS_NAME.finditer(line):
                add(m.group(1), f"{_rel(p)}:{i}")
    for p in _walk(SHELL_GLOBS, (".sh",)):
        for i, line in enumerate(_lines(p), 1):
            for m in SH_NAME.finditer(line):
                add(m.group(1), f"{_rel(p)}:{i}")
    return {k: sorted(set(v)) for k, v in sorted(found.items())}


def document(reads):
    return {
        "settings_version": 1,
        "note": "Generated by tools/settings_register.py; run it after adding or removing a setting.",
        "names": {name: {"reads": sites} for name, sites in reads.items()},
    }


def load_register():
    try:
        return json.loads(REGISTER.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return None


def write_register(reads):
    REGISTER.parent.mkdir(parents=True, exist_ok=True)
    REGISTER.write_text(json.dumps(document(reads), indent=1, sort_keys=True) + "\n", encoding="utf-8")


def check(reads) -> int:
    old = load_register()
    if old is None:
        print(f"settings register: {REGISTER.relative_to(ROOT)} is missing or unreadable; run the tool")
        return 1
    known = set((old.get("names") or {}).keys())
    now = set(reads)
    missing, extra = sorted(now - known), sorted(known - now)
    for name in missing:
        print(f"settings register: {name} is read but not in the register ({reads[name][0]})")
    for name in extra:
        print(f"settings register: {name} is in the register but no code reads it")
    if missing or extra:
        print(f"settings register: {len(missing)} missing, {len(extra)} extra; run tools/settings_register.py")
        return 1
    # the read sites are refreshed by a run; a name whose sites all vanished is caught by the name diff above
    stale = [n for n in sorted(now) if sorted(reads[n]) != (old["names"][n].get("reads") or [])]
    if stale:
        print(f"settings register: {len(stale)} entries have new read sites (a run refreshes them)")
    print(f"settings register: {len(now)} settings, no name differences")
    return 0


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="compare the scan with the register; exit 1 on a difference")
    ap.add_argument("--names", action="store_true", help="print the names that are read, one per line")
    args = ap.parse_args(argv)
    reads = scan()
    if args.names:
        print("\n".join(reads))
        return 0
    if args.check:
        return check(reads)
    write_register(reads)
    print(f"settings register: wrote {REGISTER.relative_to(ROOT)} with {len(reads)} settings")
    return 0


if __name__ == "__main__":
    sys.exit(main())
