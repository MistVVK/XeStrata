// strata_noise.hpp - Strata's own Philox noise generator: it reproduces stable-diffusion.cpp 2988060's default
// noise (--rng cuda, src/core/rng_philox.hpp) as its Linux x86 GCC build produces it, on every operating system and
// CPU, using integer arithmetic only: no maths-library call and nothing an FMA contraction can change.
// tools/image/sdcpp_noise/apply.py copies this file into a stable-diffusion.cpp checkout (src/core/) and writes the
// table below as strata_sin_exc_data.inc beside it; sd-cli uses it only with --model-args strata_noise=1.
//
// The x86 GCC stream, per value (rng_philox.hpp box_muller):
//   u = float(x) * 2^-32 + 2^-33                      (float ops; the product is exact)
//   v = float(y) * C + C/2,  C = 2^-32 * 6.2831855f   (float ops: two roundings; FMA would make it one)
//   s = float( sqrt( -2 * log(double(u)) ) )           (glibc double log, IEEE sqrt)
//   r = float( double(s) * sin(double(v)) )            (glibc double sin)
// Here log and sin are computed in 128-bit fixed point (Q8.120: 2 x uint64, 120 fraction bits, error a few units
// of 2^-120) and rounded to double; sqrt is an exact integer square root rounded to double.
//
// Where everything comes from.  All code here is our own; no third-party maths code (glibc, ARM optimized-routines,
// CORE-MATH, ...) was copied or ported.  The methods are textbook: log via ln m = ln c_j + 2 atanh(t) after a 64-point
// table step, sin/cos via angle addition from i/64 (52 table points) and Taylor series.  The constants ln 2 and pi/2
// (below) and the tables (strata_noise_tables.inc) were computed with Python's decimal module at 70 digits by
// make_tables.py, rounded to the nearest 2^-120.  The Philox4x32-10 counter logic follows the published algorithm
// (Salmon et al., SC 2011) as stable-diffusion.cpp (MIT) uses it.  The only floating-point operations left are casts
// (integer -> float, double -> float), one float multiply done exactly in double then rounded, one float add and one
// double multiply, all exactly specified by IEEE 754; the float adds are isolated by a volatile so they cannot be fused.
//
// glibc's double sin is not correctly rounded for 109,290 of the 83,886,081 reachable v (one unit off); those are
// 92,529 distinct floats, 16,761 of them listed twice with the same flag.  They are
// in strata_sin_exc.bin (packed by tools/image/gate/noise/make_sin_exceptions.py from check_domain.cpp's exhaustive
// list against glibc on x86-64, each re-checked against a 50-digit decimal sin) and compiled in through
// strata_sin_exc_data.inc (generated by apply.py).  glibc's double log is off by one unit for 21,841 reachable u, but
// the float s is the same for every one of them, so log needs no table.
// Build flag for the proof programs only: -DSTRATA_NOISE_NO_SIN_EXC leaves the table out (the correctly rounded sin).
