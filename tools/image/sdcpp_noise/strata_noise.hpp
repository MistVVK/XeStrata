struct U128 { uint64_t hi, lo; };

static inline U128 u128(uint64_t hi, uint64_t lo) { return U128{hi, lo}; }
static inline U128 add(U128 a, U128 b) { U128 r{a.hi + b.hi, a.lo + b.lo}; r.hi += r.lo < a.lo; return r; }
static inline U128 sub(U128 a, U128 b) { U128 r{a.hi - b.hi, a.lo - b.lo}; r.hi -= a.lo < b.lo; return r; }
static inline bool lt(U128 a, U128 b) { return a.hi < b.hi || (a.hi == b.hi && a.lo < b.lo); }
static inline bool is0(U128 a) { return (a.hi | a.lo) == 0; }
static inline U128 shl(U128 a, int n) {
    if (n == 0) return a;
    if (n >= 64) return U128{a.lo << (n - 64), 0};
    return U128{(a.hi << n) | (a.lo >> (64 - n)), a.lo << n};
}
static inline U128 shr(U128 a, int n) {
    if (n == 0) return a;
    if (n >= 64) return U128{0, a.hi >> (n - 64)};
    return U128{a.hi >> n, (a.lo >> n) | (a.hi << (64 - n))};
}
static inline int msb(U128 a) {   // index of the top set bit, -1 for 0
    int n = 127;
    uint64_t w = a.hi;
    if (!w) { w = a.lo; n = 63; if (!w) return -1; }
    while (!(w >> 63)) { w <<= 1; --n; }
    return n;
}
// (a * b) >> 120 (Q8.120 product, truncated), with 32-bit limbs
static inline U128 mulfx(U128 a, U128 b) {
    uint32_t x[4] = {(uint32_t) a.lo, (uint32_t) (a.lo >> 32), (uint32_t) a.hi, (uint32_t) (a.hi >> 32)};
    uint32_t y[4] = {(uint32_t) b.lo, (uint32_t) (b.lo >> 32), (uint32_t) b.hi, (uint32_t) (b.hi >> 32)};
    uint64_t r[8] = {0, 0, 0, 0, 0, 0, 0, 0};
    for (int i = 0; i < 4; ++i) {
        uint64_t c = 0;
        for (int j = 0; j < 4; ++j) {
            uint64_t t = (uint64_t) x[i] * y[j] + r[i + j] + c;
            r[i + j] = t & 0xffffffffu;
            c = t >> 32;
        }
        r[i + 4] = c;
    }
    uint64_t o[4];
    for (int k = 0; k < 4; ++k) o[k] = ((r[3 + k] >> 24) | (r[4 + k] << 8)) & 0xffffffffu;
    return U128{(o[3] << 32) | o[2], (o[1] << 32) | o[0]};
}
static inline U128 divsmall(U128 a, uint32_t d) {
    uint32_t l[4] = {(uint32_t) (a.hi >> 32), (uint32_t) a.hi, (uint32_t) (a.lo >> 32), (uint32_t) a.lo};
    uint64_t rem = 0;
    uint32_t q[4];
    for (int i = 0; i < 4; ++i) {
        uint64_t cur = (rem << 32) | l[i];
        q[i] = (uint32_t) (cur / d);
        rem = cur % d;
    }
    return U128{((uint64_t) q[0] << 32) | q[1], ((uint64_t) q[2] << 32) | q[3]};
}
static inline U128 mulsmall(U128 a, uint32_t k) {
    uint64_t l0 = (a.lo & 0xffffffffu) * k, l1 = (a.lo >> 32) * k + (l0 >> 32);
    uint64_t h0 = (a.hi & 0xffffffffu) * k + (l1 >> 32), h1 = (a.hi >> 32) * k + (h0 >> 32);
    return U128{(h1 << 32) | (h0 & 0xffffffffu), (l1 << 32) | (l0 & 0xffffffffu)};
}

static const U128 LN2  = {0x00b17217f7d1cf79ull, 0xabc9e3b39803f2f7ull};   // ln 2   * 2^120
static const U128 PIO2 = {0x01921fb54442d184ull, 0x69898cc51701b83aull};   // pi/2   * 2^120
static const U128 ONE  = {0x0100000000000000ull, 0};                       // 1      * 2^120

static inline uint64_t dbits(double d) { uint64_t b; std::memcpy(&b, &d, 8); return b; }
static inline double bitsd(uint64_t b) { double d; std::memcpy(&d, &b, 8); return d; }
static inline uint32_t fbits(float f) { uint32_t b; std::memcpy(&b, &f, 4); return b; }

// a Q8.120 magnitude (> 0) rounded to the nearest double (ties to even); value = F * 2^-120
static inline double fx_to_double(U128 f, bool neg) {
    int p = msb(f);
    if (p < 0) return neg ? -0.0 : 0.0;
    uint64_t mant;
    bool up = false;
    if (p >= 52) {
        int drop = p - 52;
        U128 m = shr(f, drop);
        mant = m.lo;
        if (drop > 0) {
            U128 rest = sub(f, shl(m, drop));
            U128 half = shl(u128(0, 1), drop - 1);
            if (lt(half, rest)) up = true;
            else if (!lt(rest, half) && !lt(half, rest)) up = (mant & 1);   // exact tie
        }
    } else {
        mant = shl(f, 52 - p).lo;
    }
    int e = p - 120;               // value = mant * 2^(e - 52)
    if (up && ++mant == (1ull << 53)) { mant >>= 1; ++e; }
    uint64_t bits = ((uint64_t) (e + 1023) << 52) | (mant & ((1ull << 52) - 1));
    return bitsd(bits | (neg ? (1ull << 63) : 0));
}

