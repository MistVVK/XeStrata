"""tools/image/gate/te_tok_tables.py - TEST-ONLY generator: src/image/te/qwen2_tok_unicode.inc from te_tok_probe's
"classes" dump (Oniguruma's \\p{L}, \\p{N}, \\s and the case folds of s t r e v m l d, as stable-diffusion.cpp's
Qwen2 pre-tokenizer sees them).

    python -I -B te_tok_tables.py <classes.txt> <out .inc>"""
import sys
from pathlib import Path

NAMES = {"L": "kUniL", "N": "kUniN", "S": "kUniS", "fs": "kFold_s", "ft": "kFold_t", "fr": "kFold_r", "fe": "kFold_e",
         "fv": "kFold_v", "fm": "kFold_m", "fl": "kFold_l", "fd": "kFold_d"}


def main() -> int:
    src, out = Path(sys.argv[1]), Path(sys.argv[2])
    ranges = {k: [] for k in NAMES}
    for line in src.read_text().splitlines():
        k, a, b = line.split()
        ranges[k].append((int(a), int(b)))
    lines = ["// src/image/te/qwen2_tok_unicode.inc - GENERATED by tools/image/gate/te_tok_tables.py from te_tok_probe's dump of",
             "// stable-diffusion.cpp 2988060's Oniguruma (UTF-8): code point ranges [first, last] of \\p{L}, \\p{N}, \\s and of the",
             "// case-insensitive matches of the letters in Qwen2's contractions.  Do not edit; regenerate from the probe."]
    for k, name in NAMES.items():
        r = sorted(ranges[k])
        assert r, f"class {k} is empty"
        assert all(r[i][1] < r[i + 1][0] for i in range(len(r) - 1)), f"class {k} not disjoint"
        lines.append(f"static const uint32_t {name}[][2] = {{  // {len(r)} ranges, {sum(b - a + 1 for a, b in r)} code points")
        row = []
        for a, b in r:
            row.append(f"{{{a:#x}, {b:#x}}}")
            if len(row) == 6:
                lines.append("    " + ", ".join(row) + ",")
                row = []
        if row:
            lines.append("    " + ", ".join(row) + ",")
        lines.append("};")
    out.write_text("\n".join(lines) + "\n")
    print(f"{out}: " + ", ".join(f"{k} {len(v)}" for k, v in ranges.items()))
    return 0


if __name__ == "__main__":
    sys.exit(main())
