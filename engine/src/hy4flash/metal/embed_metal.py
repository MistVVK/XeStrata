#!/usr/bin/env python3
# embed_metal.py OUT.inc FILE.metal... : writes a C++ include with the MSL sources as byte arrays, so strata-hy4-metal needs no kernel files next to it
# (the Command Line Tools have no offline `metal` compiler: the kernels are compiled at run time from these embedded sources).
import os
import sys

out = sys.argv[1]
files = sys.argv[2:]
with open(out, 'w') as f:
    f.write('// generated by embed_metal.py: do not edit\n')
    for i, p in enumerate(files):
        data = open(p, 'rb').read()
        f.write('static const unsigned char hy4_emb_%d[] = {' % i)
        f.write(','.join(str(b) for b in data))
        f.write('};\n')
    f.write('struct Hy4EmbFile { const char* name; const unsigned char* data; unsigned long size; };\n')
    f.write('static const Hy4EmbFile hy4_emb_files[] = {\n')
    for i, p in enumerate(files):
        f.write('    {"%s", hy4_emb_%d, sizeof(hy4_emb_%d)},\n' % (os.path.basename(p), i, i))
    f.write('};\n')
